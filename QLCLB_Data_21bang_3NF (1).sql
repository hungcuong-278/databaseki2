-- ============================================================================
-- Football club management database (FC Barcelona) - 21 relations, 3NF
-- Version 2   : after Part IV decomposition
--               TranDau  -> TranDau (6a) + SanVanDong (6b)
--               CauLacBo -> CauLacBo (18a) + ThanhPho (18b)
-- Target DBMS : MySQL 8.0.16+ (CHECK constraints enforced); MariaDB 10.6+ OK
-- Note        : TranDau.GiaVe stores a PRICE MULTIPLIER (1.0, 1.2, ...).
--               Actual ticket price = KhanDai.GiaVeCoBan * TranDau.GiaVe
-- ============================================================================
SET NAMES utf8mb4;

DROP DATABASE IF EXISTS QLCLB;
CREATE DATABASE QLCLB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE QLCLB;

-- 18b. City (decomposed from CauLacBo: ThanhPho -> QuocGia)
CREATE TABLE ThanhPho (
    ThanhPho     VARCHAR(50)  NOT NULL,
    QuocGia      VARCHAR(50)  NOT NULL,
    PRIMARY KEY (ThanhPho)
);

-- 18a. Club
CREATE TABLE CauLacBo (
    MaCLB        VARCHAR(10)  NOT NULL,
    TenCLB       VARCHAR(100) NOT NULL,
    ThanhPho     VARCHAR(50)  NOT NULL,
    SanNha       VARCHAR(100),
    NamThanhLap  SMALLINT,
    Email        VARCHAR(100),
    PRIMARY KEY (MaCLB),
    CONSTRAINT fk_clb_tp FOREIGN KEY (ThanhPho) REFERENCES ThanhPho (ThanhPho),
    UNIQUE KEY uq_clb_email (Email),
    CHECK (NamThanhLap BETWEEN 1800 AND 2100),
    CHECK (Email IS NULL OR Email LIKE '%_@_%._%')
);

-- 19. Club phone numbers (multi-valued attribute)
CREATE TABLE CauLacBo_SoDienThoai (
    MaCLB        VARCHAR(10) NOT NULL,
    SoDienThoai  VARCHAR(10) NOT NULL,
    PRIMARY KEY (MaCLB, SoDienThoai),
    UNIQUE KEY uq_clb_sdt (SoDienThoai),
    CONSTRAINT fk_clbsdt_clb FOREIGN KEY (MaCLB) REFERENCES CauLacBo (MaCLB),
    CHECK (SoDienThoai REGEXP '^0[0-9]{9}$')
);

-- 7. Competition
CREATE TABLE GiaiDau (
    MaGiaiDau    VARCHAR(10)  NOT NULL,
    TenGiai      VARCHAR(100) NOT NULL,
    MuaGiai      VARCHAR(9)   NOT NULL,
    LoaiGiai     VARCHAR(50)  NOT NULL,
    DonViToChuc  VARCHAR(50),
    NgayBatDau   DATE NOT NULL,
    NgayKetThuc  DATE NOT NULL,
    PRIMARY KEY (MaGiaiDau),
    UNIQUE KEY uq_giai_mua (TenGiai, MuaGiai),
    CHECK (LoaiGiai IN ('Vô địch quốc gia', 'Cúp quốc gia', 'Cúp châu lục', 'Giao hữu')),
    CHECK (NgayBatDau < NgayKetThuc)
);

-- 5. Stand
CREATE TABLE KhanDai (
    MaKhanDai    VARCHAR(10) NOT NULL,
    TenKhanDai   VARCHAR(50) NOT NULL,
    SucChua      INT NOT NULL,
    GiaVeCoBan   DECIMAL(15,0) NOT NULL,
    TrangThai    VARCHAR(30) NOT NULL,
    PRIMARY KEY (MaKhanDai),
    CHECK (SucChua > 0),
    CHECK (GiaVeCoBan > 0),
    CHECK (TrangThai IN ('Hoạt động', 'Đang sửa chữa'))
);

-- 10. Personnel (superclass of CauThu / HuanLuyenVien / NhanVienVanPhong)
CREATE TABLE NhanSu (
    MaNhanSu        VARCHAR(10)  NOT NULL,
    HoTen           VARCHAR(100) NOT NULL,
    NgaySinh        DATE NOT NULL,
    GioiTinh        VARCHAR(5)   NOT NULL,
    QuocTich        VARCHAR(50)  NOT NULL,
    SoCCCD          VARCHAR(20)  NOT NULL,
    DiaChi          VARCHAR(255),
    Email           VARCHAR(100),
    NgayGiaNhapCLB  DATE NOT NULL,
    LoaiNhanSu      VARCHAR(3)   NOT NULL,
    PRIMARY KEY (MaNhanSu),
    UNIQUE KEY uq_ns_cccd (SoCCCD),
    UNIQUE KEY uq_ns_email (Email),
    CHECK (GioiTinh IN ('Nam', 'Nữ')),
    CHECK (LoaiNhanSu IN ('CT', 'HLV', 'NV')),
    CHECK (Email IS NULL OR Email LIKE '%_@_%._%'),
    CHECK (NgaySinh < NgayGiaNhapCLB)
);

-- 11. Personnel phone numbers (multi-valued attribute)
CREATE TABLE NhanSu_SoDienThoai (
    MaNhanSu     VARCHAR(10) NOT NULL,
    SoDienThoai  VARCHAR(10) NOT NULL,
    PRIMARY KEY (MaNhanSu, SoDienThoai),
    UNIQUE KEY uq_ns_sdt (SoDienThoai),
    CONSTRAINT fk_nssdt_ns FOREIGN KEY (MaNhanSu) REFERENCES NhanSu (MaNhanSu),
    CHECK (SoDienThoai REGEXP '^0[0-9]{9}$')
);

-- 15. Player (subclass of NhanSu)
CREATE TABLE CauThu (
    CT_MaNhanSu  VARCHAR(10) NOT NULL,
    SoAo         TINYINT UNSIGNED NOT NULL,
    ViTri        VARCHAR(20) NOT NULL,
    ChanThuan    VARCHAR(10),
    ChieuCao     SMALLINT,
    CanNang      SMALLINT,
    TrangThai    VARCHAR(30) NOT NULL,
    PRIMARY KEY (CT_MaNhanSu),
    CONSTRAINT fk_ct_ns FOREIGN KEY (CT_MaNhanSu) REFERENCES NhanSu (MaNhanSu),
    CHECK (SoAo BETWEEN 1 AND 99),
    CHECK (ViTri IN ('Thủ môn', 'Hậu vệ', 'Tiền vệ', 'Tiền đạo')),
    CHECK (ChanThuan IN ('Trái', 'Phải', 'Hai chân')),
    CHECK (ChieuCao BETWEEN 150 AND 215),
    CHECK (CanNang BETWEEN 45 AND 120),
    CHECK (TrangThai IN ('Đang thi đấu', 'Đang cho mượn', 'Chấn thương', 'Đã rời CLB'))
);

-- 13. Coach (subclass of NhanSu)
CREATE TABLE HuanLuyenVien (
    HLV_MaNhanSu       VARCHAR(10) NOT NULL,
    ChucDanh           VARCHAR(50) NOT NULL,
    HangBangHuanLuyen  VARCHAR(10),
    ChuyenMon          VARCHAR(100),
    PRIMARY KEY (HLV_MaNhanSu),
    CONSTRAINT fk_hlv_ns FOREIGN KEY (HLV_MaNhanSu) REFERENCES NhanSu (MaNhanSu),
    CHECK (ChucDanh IN ('HLV trưởng', 'HLV phó', 'HLV thủ môn', 'HLV thể lực', 'HLV phân tích')),
    CHECK (HangBangHuanLuyen IN ('Pro', 'A', 'B', 'C'))
);

-- 14. Office staff (subclass of NhanSu)
CREATE TABLE NhanVienVanPhong (
    NVVP_MaNhanSu  VARCHAR(10) NOT NULL,
    BoPhan         VARCHAR(50) NOT NULL,
    ChucVu         VARCHAR(50) NOT NULL,
    PRIMARY KEY (NVVP_MaNhanSu),
    CONSTRAINT fk_nvvp_ns FOREIGN KEY (NVVP_MaNhanSu) REFERENCES NhanSu (MaNhanSu),
    CHECK (BoPhan IN ('Kế toán', 'Truyền thông', 'Y tế', 'Bán vé', 'Hành chính', 'Kỹ thuật sân bãi'))
);

-- 12. Employment contract (one personnel -> many contracts over time)
CREATE TABLE HopDongLaoDong (
    MaHopDong     VARCHAR(10) NOT NULL,
    MaNhanSu      VARCHAR(10) NOT NULL,
    LoaiHopDong   VARCHAR(30) NOT NULL,
    NgayKy        DATE NOT NULL,
    NgayBatDau    DATE NOT NULL,
    NgayKetThuc   DATE NOT NULL,
    LuongThang    DECIMAL(15,0) NOT NULL,
    PhiGiaiPhong  DECIMAL(15,0) NULL,   -- release clause: players only
    TrangThai     VARCHAR(30) NOT NULL,
    PRIMARY KEY (MaHopDong),
    CONSTRAINT fk_hd_ns FOREIGN KEY (MaNhanSu) REFERENCES NhanSu (MaNhanSu),
    CHECK (LoaiHopDong IN ('Chính thức', 'Thử việc', 'Cho mượn', 'Cầu thủ trẻ')),
    CHECK (TrangThai IN ('Hiệu lực', 'Hết hạn', 'Chấm dứt trước hạn')),
    CHECK (NgayKy <= NgayBatDau AND NgayBatDau < NgayKetThuc),
    CHECK (LuongThang > 0),
    CHECK (PhiGiaiPhong IS NULL OR PhiGiaiPhong > 0)
);

-- 1. Account (MaNhanSu NULL = fan account)
CREATE TABLE TaiKhoan (
    MaTaiKhoan    VARCHAR(10)  NOT NULL,
    MaNhanSu      VARCHAR(10)  NULL,
    TenDangNhap   VARCHAR(50)  NOT NULL,
    MatKhau       VARCHAR(255) NOT NULL,
    Email         VARCHAR(100) NOT NULL,
    HoTenHienThi  VARCHAR(100) NOT NULL,
    VaiTro        VARCHAR(30)  NOT NULL,
    TrangThai     VARCHAR(30)  NOT NULL,
    NgayTao       DATE NOT NULL,
    PRIMARY KEY (MaTaiKhoan),
    UNIQUE KEY uq_tk_user (TenDangNhap),
    UNIQUE KEY uq_tk_email (Email),
    UNIQUE KEY uq_tk_ns (MaNhanSu),
    CONSTRAINT fk_tk_ns FOREIGN KEY (MaNhanSu) REFERENCES NhanSu (MaNhanSu),
    CHECK (VaiTro IN ('Quản trị viên', 'Biên tập viên', 'Nhân viên bán vé', 'Người hâm mộ')),
    CHECK (TrangThai IN ('Hoạt động', 'Chưa xác thực', 'Bị khoá')),
    CHECK (Email LIKE '%_@_%._%'),
    -- staff roles must link to a personnel record; fan accounts must not
    CHECK ((VaiTro = 'Người hâm mộ') = (MaNhanSu IS NULL))
);

-- 2. Account phone numbers (multi-valued attribute)
CREATE TABLE TaiKhoan_SoDienThoai (
    MaTaiKhoan   VARCHAR(10) NOT NULL,
    SoDienThoai  VARCHAR(10) NOT NULL,
    PRIMARY KEY (MaTaiKhoan, SoDienThoai),
    UNIQUE KEY uq_tk_sdt (SoDienThoai),
    CONSTRAINT fk_tksdt_tk FOREIGN KEY (MaTaiKhoan) REFERENCES TaiKhoan (MaTaiKhoan),
    CHECK (SoDienThoai REGEXP '^0[0-9]{9}$')
);

-- 6b. Stadium (decomposed from TranDau: TenSanVanDong -> DiaDiem).
--     DiaDiem is seen from FC Barcelona's side: home / away / neutral ground.
CREATE TABLE SanVanDong (
    TenSanVanDong  VARCHAR(100) NOT NULL,
    DiaDiem        VARCHAR(20)  NOT NULL,
    PRIMARY KEY (TenSanVanDong),
    CHECK (DiaDiem IN ('Sân nhà', 'Sân khách', 'Sân trung lập'))
);

-- 6a. Match (GiaVe = ticket price multiplier, NULL for away/neutral matches)
CREATE TABLE TranDau (
    MaTran          VARCHAR(10)  NOT NULL,
    MaGiaiDau       VARCHAR(10)  NOT NULL,
    MaCLB           VARCHAR(10)  NOT NULL,   -- opponent club
    VongDau         VARCHAR(20)  NOT NULL,
    ThoiGianThiDau  DATETIME     NOT NULL,
    TenSanVanDong   VARCHAR(100) NOT NULL,
    SoBanThang      TINYINT UNSIGNED NULL,
    SoBanThua       TINYINT UNSIGNED NULL,
    GiaVe           DECIMAL(3,1) NULL COMMENT 'Ticket price multiplier',
    TrangThai       VARCHAR(20)  NOT NULL,
    PRIMARY KEY (MaTran),
    CONSTRAINT fk_td_gd  FOREIGN KEY (MaGiaiDau) REFERENCES GiaiDau (MaGiaiDau),
    CONSTRAINT fk_td_clb FOREIGN KEY (MaCLB)     REFERENCES CauLacBo (MaCLB),
    CONSTRAINT fk_td_svd FOREIGN KEY (TenSanVanDong) REFERENCES SanVanDong (TenSanVanDong),
    CHECK (TrangThai IN ('Sắp diễn ra', 'Đang diễn ra', 'Đã kết thúc', 'Hoãn', 'Huỷ')),
    CHECK (GiaVe IS NULL OR GiaVe > 0),   -- home-only rule: see triggers below
    CHECK ((TrangThai = 'Đã kết thúc') = (SoBanThang IS NOT NULL AND SoBanThua IS NOT NULL))
);

-- 3. News article (MaTran NULL = article not tied to a match)
CREATE TABLE TinTuc (
    MaBaiViet    VARCHAR(10)  NOT NULL,
    MaTaiKhoan   VARCHAR(10)  NOT NULL,
    MaTran       VARCHAR(10)  NULL,
    TieuDe       VARCHAR(255) NOT NULL,
    TomTat       VARCHAR(500),
    NoiDung      TEXT NOT NULL,
    ChuyenMuc    VARCHAR(50)  NOT NULL,
    NgayTao      DATE NOT NULL,
    NgayXuatBan  DATE NULL,
    TrangThai    VARCHAR(20)  NOT NULL,
    LuotXem      INT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (MaBaiViet),
    CONSTRAINT fk_tt_tk FOREIGN KEY (MaTaiKhoan) REFERENCES TaiKhoan (MaTaiKhoan),
    CONSTRAINT fk_tt_td FOREIGN KEY (MaTran)     REFERENCES TranDau (MaTran),
    CHECK (ChuyenMuc IN ('Tin CLB', 'Tường thuật trận đấu', 'Chuyển nhượng', 'Thông báo bán vé')),
    CHECK (TrangThai IN ('Nháp', 'Chờ duyệt', 'Đã xuất bản', 'Đã ẩn')),
    CHECK (TrangThai <> 'Đã xuất bản' OR NgayXuatBan IS NOT NULL),
    CHECK (ChuyenMuc <> 'Tường thuật trận đấu' OR MaTran IS NOT NULL),
    CHECK (NgayXuatBan IS NULL OR NgayXuatBan >= NgayTao)
);

-- 4. Ticket (seat uniqueness among non-cancelled tickets is a business rule
--    checked by the application/trigger, so no plain UNIQUE on the seat triple)
CREATE TABLE Ve (
    MaVe                 VARCHAR(10) NOT NULL,
    MaTaiKhoan           VARCHAR(10) NOT NULL,
    MaTran               VARCHAR(10) NOT NULL,
    MaKhanDai            VARCHAR(10) NOT NULL,
    SoVe                 INT UNSIGNED NOT NULL,
    KenhBan              VARCHAR(20) NOT NULL,
    ThoiDiemMua          DATETIME NOT NULL,
    GiaBan               DECIMAL(15,0) NOT NULL,
    PhuongThucThanhToan  VARCHAR(30) NOT NULL,
    TrangThai            VARCHAR(20) NOT NULL,
    PRIMARY KEY (MaVe),
    KEY idx_ve_ghe (MaTran, MaKhanDai, SoVe),
    CONSTRAINT fk_ve_tk FOREIGN KEY (MaTaiKhoan) REFERENCES TaiKhoan (MaTaiKhoan),
    CONSTRAINT fk_ve_td FOREIGN KEY (MaTran)     REFERENCES TranDau (MaTran),
    CONSTRAINT fk_ve_kd FOREIGN KEY (MaKhanDai)  REFERENCES KhanDai (MaKhanDai),
    CHECK (SoVe > 0),
    CHECK (GiaBan > 0),
    CHECK (KenhBan IN ('Trực tuyến', 'Tại quầy')),
    CHECK (PhuongThucThanhToan IN ('Thẻ', 'Ví điện tử', 'Chuyển khoản', 'Tiền mặt')),
    CHECK (TrangThai IN ('Chờ thanh toán', 'Đã thanh toán', 'Đã huỷ', 'Đã sử dụng')),
    CHECK (NOT (KenhBan = 'Trực tuyến' AND PhuongThucThanhToan = 'Tiền mặt'))
);

-- 9. Match lineup (DiemDanhGia NULL = unused substitute)
CREATE TABLE DoiHinhThiDau (
    MaTran       VARCHAR(10) NOT NULL,
    CT_MaNhanSu  VARCHAR(10) NOT NULL,
    VaiTro       VARCHAR(20) NOT NULL,
    ViTriThiDau  VARCHAR(20) NOT NULL,
    CapBac       VARCHAR(20) NOT NULL,
    DiemDanhGia  DECIMAL(3,1) NULL,
    PRIMARY KEY (MaTran, CT_MaNhanSu),
    CONSTRAINT fk_dh_td FOREIGN KEY (MaTran)      REFERENCES TranDau (MaTran),
    CONSTRAINT fk_dh_ct FOREIGN KEY (CT_MaNhanSu) REFERENCES CauThu (CT_MaNhanSu),
    CHECK (VaiTro IN ('Đá chính', 'Dự bị')),
    CHECK (ViTriThiDau IN ('Thủ môn', 'Hậu vệ', 'Tiền vệ', 'Tiền đạo')),
    CHECK (CapBac IN ('Đội trưởng', 'Đội phó', 'Cầu thủ')),
    CHECK (DiemDanhGia IS NULL OR DiemDanhGia BETWEEN 0 AND 10)
);

-- 8. Match event (self reference: Kiến tạo -> Bàn thắng, Vào sân -> Rời sân,
--    Thẻ đỏ -> second Thẻ vàng)
CREATE TABLE SuKienTranDau (
    MaSuKien          VARCHAR(10) NOT NULL,
    MaTran            VARCHAR(10) NOT NULL,
    CT_MaNhanSu       VARCHAR(10) NOT NULL,
    MaSuKienLienQuan  VARCHAR(10) NULL,
    Phut              TINYINT UNSIGNED NOT NULL,
    LoaiSuKien        VARCHAR(20) NOT NULL,
    GhiChu            VARCHAR(255),
    PRIMARY KEY (MaSuKien),
    CONSTRAINT fk_sk_dh  FOREIGN KEY (MaTran, CT_MaNhanSu)
        REFERENCES DoiHinhThiDau (MaTran, CT_MaNhanSu),
    CONSTRAINT fk_sk_td  FOREIGN KEY (MaTran)           REFERENCES TranDau (MaTran),
    CONSTRAINT fk_sk_ct  FOREIGN KEY (CT_MaNhanSu)      REFERENCES CauThu (CT_MaNhanSu),
    CONSTRAINT fk_sk_lq  FOREIGN KEY (MaSuKienLienQuan) REFERENCES SuKienTranDau (MaSuKien),
    CHECK (Phut BETWEEN 1 AND 120),
    CHECK (LoaiSuKien IN ('Bàn thắng', 'Kiến tạo', 'Phản lưới nhà', 'Thẻ vàng',
                          'Thẻ đỏ', 'Vào sân', 'Rời sân')),
    CHECK (MaSuKienLienQuan IS NULL OR MaSuKienLienQuan <> MaSuKien)
);

-- 16. Injury (MaTran NULL = injury outside a match, e.g. training)
CREATE TABLE ChanThuong (
    MaChanThuong      VARCHAR(10) NOT NULL,
    CT_MaNhanSu       VARCHAR(10) NOT NULL,
    MaTran            VARCHAR(10) NULL,
    LoaiChanThuong    VARCHAR(100) NOT NULL,
    ViTriTrenCoThe    VARCHAR(50),
    MucDo             VARCHAR(20) NOT NULL,
    NgayChanThuong    DATE NOT NULL,
    NgayDuKienTroLai  DATE NULL,
    NgayTroLaiThucTe  DATE NULL,
    PRIMARY KEY (MaChanThuong),
    CONSTRAINT fk_cth_ct FOREIGN KEY (CT_MaNhanSu) REFERENCES CauThu (CT_MaNhanSu),
    CONSTRAINT fk_cth_td FOREIGN KEY (MaTran)      REFERENCES TranDau (MaTran),
    CHECK (MucDo IN ('Nhẹ', 'Trung bình', 'Nặng')),
    CHECK (NgayDuKienTroLai IS NULL OR NgayDuKienTroLai >= NgayChanThuong),
    CHECK (NgayTroLaiThucTe IS NULL OR NgayTroLaiThucTe >= NgayChanThuong)
);

-- 17. Transfer (MaCLB NULL = free transfer)
CREATE TABLE PhienChuyenNhuong (
    MaChuyenNhuong    VARCHAR(10) NOT NULL,
    CT_MaNhanSu       VARCHAR(10) NOT NULL,
    MaCLB             VARCHAR(10) NULL,
    LoaiChuyenNhuong  VARCHAR(20) NOT NULL,
    NgayThucHien      DATE NOT NULL,
    PhiChuyenNhuong   DECIMAL(15,0) NOT NULL DEFAULT 0,
    TrangThai         VARCHAR(20) NOT NULL,
    PRIMARY KEY (MaChuyenNhuong),
    CONSTRAINT fk_cn_ct  FOREIGN KEY (CT_MaNhanSu) REFERENCES CauThu (CT_MaNhanSu),
    CONSTRAINT fk_cn_clb FOREIGN KEY (MaCLB)       REFERENCES CauLacBo (MaCLB),
    CHECK (LoaiChuyenNhuong IN ('Mua vào', 'Bán đi', 'Cho mượn', 'Mượn về', 'Tự do')),
    CHECK (TrangThai IN ('Đang đàm phán', 'Hoàn tất', 'Huỷ')),
    CHECK (PhiChuyenNhuong >= 0),
    CHECK (LoaiChuyenNhuong <> 'Tự do' OR PhiChuyenNhuong = 0),
    CHECK ((LoaiChuyenNhuong = 'Tự do') = (MaCLB IS NULL))
);

-- ----------------------------------------------------------------------------
-- After the decomposition DiaDiem lives in SanVanDong, so the rule
-- "a ticket price multiplier exists only for home matches" can no longer be a
-- CHECK on TranDau. Two triggers enforce it on INSERT and UPDATE.
-- ----------------------------------------------------------------------------
DELIMITER $$

CREATE TRIGGER trg_trandau_giave_bi
BEFORE INSERT ON TranDau
FOR EACH ROW
BEGIN
    IF NEW.GiaVe IS NOT NULL AND
       (SELECT DiaDiem FROM SanVanDong WHERE TenSanVanDong = NEW.TenSanVanDong) <> 'Sân nhà' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'GiaVe chi duoc nhap cho tran dau tren san nha';
    END IF;
END$$

CREATE TRIGGER trg_trandau_giave_bu
BEFORE UPDATE ON TranDau
FOR EACH ROW
BEGIN
    IF NEW.GiaVe IS NOT NULL AND
       (SELECT DiaDiem FROM SanVanDong WHERE TenSanVanDong = NEW.TenSanVanDong) <> 'Sân nhà' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'GiaVe chi duoc nhap cho tran dau tren san nha';
    END IF;
END$$

DELIMITER ;

